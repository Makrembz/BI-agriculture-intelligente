-- ------------------------------- FAITS -------------------------------
CREATE TABLE dwh.fait_declaration_irrigation (
    id_declaration            text PRIMARY KEY,             -- dimension degeneree
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,       -- 1er janvier de l'annee declaree
    sk_comte                  integer NOT NULL REFERENCES dwh.dim_comte,
    sk_exploitant             integer NOT NULL REFERENCES dwh.dim_exploitant,
    sk_culture                integer NOT NULL REFERENCES dwh.dim_culture,
    sk_source_eau             integer NOT NULL REFERENCES dwh.dim_source_eau,
    sk_type_droit             integer NOT NULL REFERENCES dwh.dim_type_droit,
    volume_autorise_acft      numeric(16,3),
    volume_declare_acft       numeric(16,3),                -- extension : volume utilise declare, si la source le fournit
    surface_irriguee_acres    numeric(14,3),
    nb_declarations           smallint NOT NULL DEFAULT 1,
    nb_champs_renseignes      smallint,
    nb_champs_attendus        smallint,
    indicateur_culture_renseignee smallint
);

CREATE TABLE dwh.fait_et_mensuelle_comte (
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,       -- 1er jour du mois
    sk_comte                  integer NOT NULL REFERENCES dwh.dim_comte,
    et_moyenne_acft           numeric(16,3),
    et_moyenne_pouces         numeric(10,4),
    et_min_modeles_acft       numeric(16,3),
    et_max_modeles_acft       numeric(16,3),
    et_ecart_type_modeles_acft numeric(16,3),
    nb_modeles_renseignes     smallint,
    PRIMARY KEY (sk_temps, sk_comte)
);

CREATE TABLE dwh.fait_et_mensuelle_bassin (
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,
    sk_bassin                 integer NOT NULL REFERENCES dwh.dim_bassin,
    et_moyenne_acft           numeric(16,3),
    et_moyenne_pouces         numeric(10,4),
    et_min_modeles_acft       numeric(16,3),
    et_max_modeles_acft       numeric(16,3),
    et_ecart_type_modeles_acft numeric(16,3),
    nb_modeles_renseignes     smallint,
    PRIMARY KEY (sk_temps, sk_bassin)
);

CREATE TABLE dwh.fait_meteo_jour (
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,
    sk_comte                  integer NOT NULL REFERENCES dwh.dim_comte,       -- comte de reference de la vallee
    temperature_min_c         numeric(6,2),
    temperature_max_c         numeric(6,2),
    temperature_moy_c         numeric(6,2),
    precipitations_mm         numeric(8,2),
    et0_mm                    numeric(8,2),
    humidite_relative_pct     numeric(6,2),
    vent_kmh                  numeric(7,2),
    rayonnement_mjm2          numeric(8,2),
    humidite_sol_m3m3         numeric(7,4),
    temperature_sol_c         numeric(6,2),
    PRIMARY KEY (sk_temps, sk_comte)
);

CREATE TABLE dwh.fait_releve_capteur (
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,
    sk_capteur                integer NOT NULL REFERENCES dwh.dim_capteur,
    sk_parcelle               integer NOT NULL REFERENCES dwh.dim_parcelle,
    sk_comte                  integer NOT NULL REFERENCES dwh.dim_comte,
    humidite_sol_m3m3         numeric(7,4),
    temperature_sol_c         numeric(6,2),
    ph                        numeric(5,2),
    conductivite_dsm          numeric(7,3),                 -- dS/m
    indicateur_alerte         smallint NOT NULL DEFAULT 0,
    indicateur_capteur_actif  smallint NOT NULL DEFAULT 1,
    PRIMARY KEY (sk_temps, sk_capteur)
);

CREATE TABLE dwh.fait_prediction (
    id_prediction             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sk_temps                  integer NOT NULL REFERENCES dwh.dim_temps,
    sk_comte                  integer NOT NULL DEFAULT -1 REFERENCES dwh.dim_comte,
    sk_exploitant             integer NOT NULL DEFAULT -1 REFERENCES dwh.dim_exploitant,
    nom_modele                text NOT NULL,                -- dimensions degenerees
    version_modele            text NOT NULL,
    type_prediction           text NOT NULL,                -- demande_mensuelle | prevision_12_mois | anomalie_declaration | segment_exploitant
    date_calcul               timestamp NOT NULL DEFAULT now(),
    id_declaration            text,                         -- extension : declaration visee (anomalies)
    motif_anomalie            text,                         -- extension : raison du signalement
    valeur_predite            numeric(16,3),
    borne_basse               numeric(16,3),
    borne_haute               numeric(16,3),
    valeur_observee           numeric(16,3),
    erreur_absolue            numeric(16,3),
    score_anomalie            numeric(10,5),
    indicateur_anomalie       smallint,
    numero_segment            smallint
);

-- Tables d'appui (extensions) : comparaison des modeles et libelles des segments
CREATE TABLE dwh.ref_modele_evaluation (
    nom_modele                text NOT NULL,
    version_modele            text NOT NULL,
    cible                     text NOT NULL,
    perimetre                 text,
    metrique                  text NOT NULL,
    valeur                    numeric(18,5),
    retenu                    boolean NOT NULL DEFAULT false,
    date_calcul               timestamp NOT NULL DEFAULT now()
);

CREATE TABLE dwh.ref_segment (
    numero_segment            smallint PRIMARY KEY,
    libelle_segment           text NOT NULL,
    nb_exploitants            integer,
    volume_moyen_acft         numeric(16,2),
    surface_moyenne_acres     numeric(14,2),
    part_eau_souterraine      numeric(6,4),
    nb_cultures_moyen         numeric(6,2)
);

-- Index sur les cles etrangeres des gros faits
CREATE INDEX ix_decl_temps   ON dwh.fait_declaration_irrigation (sk_temps);
CREATE INDEX ix_decl_comte   ON dwh.fait_declaration_irrigation (sk_comte);
CREATE INDEX ix_decl_expl    ON dwh.fait_declaration_irrigation (sk_exploitant);
CREATE INDEX ix_decl_culture ON dwh.fait_declaration_irrigation (sk_culture);
CREATE INDEX ix_capt_capteur ON dwh.fait_releve_capteur (sk_capteur);
CREATE INDEX ix_capt_parc    ON dwh.fait_releve_capteur (sk_parcelle);
CREATE INDEX ix_pred_type    ON dwh.fait_prediction (type_prediction);
CREATE INDEX ix_pred_decl    ON dwh.fait_prediction (id_declaration);

-- ------------------------- SUIVI DE L'ETL ---------------------------
CREATE TABLE etl.journal (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    horodatage    timestamp NOT NULL DEFAULT now(),
    etape         text NOT NULL,
    mode_donnees  text NOT NULL,          -- 'reel' ou 'demo'
    message       text
);
CREATE TABLE etl.rejets (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    horodatage    timestamp NOT NULL DEFAULT now(),
    fait          text NOT NULL,
    motif         text NOT NULL,
    nb_lignes     bigint NOT NULL
);
CREATE TABLE etl.controle (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    horodatage    timestamp NOT NULL DEFAULT now(),
    controle      text NOT NULL,
    attendu       numeric(20,3),
    obtenu        numeric(20,3),
    ecart         numeric(20,3),
    statut        text NOT NULL            -- OK / ALERTE
);
