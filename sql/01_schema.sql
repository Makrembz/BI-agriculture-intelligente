-- =====================================================================
--  Entrepot de donnees BI Agriculture Intelligente  (constellation de faits)
--  PostgreSQL 14+ . Rejouable : supprime et recree les schemas dwh et etl.
--  Les cles de substitution sont notees sk_* ; la cle -1 = membre "inconnu".
-- =====================================================================
DROP SCHEMA IF EXISTS dwh CASCADE;
DROP SCHEMA IF EXISTS etl CASCADE;
CREATE SCHEMA dwh;
CREATE SCHEMA etl;

-- ------------------------------ DIMENSIONS ---------------------------
CREATE TABLE dwh.dim_temps (
    sk_temps              integer PRIMARY KEY,             -- yyyymmdd ; -1 = inconnu
    date                  date UNIQUE,
    annee                 smallint,
    annee_hydrologique    smallint,                        -- octobre a septembre
    trimestre             smallint,
    mois                  smallint,
    nom_mois              text,
    annee_mois            text,                            -- 'YYYY-MM' (tri Power BI)
    jour                  smallint,
    jour_semaine          smallint,                        -- 1 = lundi
    nom_jour_semaine      text,
    est_premier_jour_mois boolean
);

CREATE TABLE dwh.dim_comte (
    sk_comte              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_comte            text NOT NULL UNIQUE,
    nom_comte             text NOT NULL,
    vallee_agricole       text,
    surface_agricole_acres numeric(14,2),
    latitude_ref          numeric(9,5),
    longitude_ref         numeric(9,5)
);

CREATE TABLE dwh.dim_exploitant (
    sk_exploitant         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_exploitant_source  text NOT NULL UNIQUE,
    nom_exploitant        text,
    nb_comtes_actifs      smallint
);

CREATE TABLE dwh.dim_culture (
    sk_culture            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_culture          text NOT NULL UNIQUE,
    nom_culture           text NOT NULL,
    famille_culture       text,
    est_renseignee        boolean NOT NULL DEFAULT true
);

CREATE TABLE dwh.dim_source_eau (
    sk_source_eau         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_source           text NOT NULL UNIQUE,
    libelle_source        text NOT NULL,
    categorie_source      text
);

CREATE TABLE dwh.dim_type_droit (
    sk_type_droit         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_type_droit       text NOT NULL UNIQUE,
    libelle_type_droit    text NOT NULL
);

CREATE TABLE dwh.dim_bassin (
    sk_bassin             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_bassin           text NOT NULL UNIQUE,
    nom_bassin            text NOT NULL
);

CREATE TABLE dwh.dim_parcelle (
    sk_parcelle           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parcelle           text NOT NULL UNIQUE,
    surface_acres         numeric(10,2),
    culture_dominante     text,
    latitude              numeric(9,5),
    longitude             numeric(9,5),
    origine               text                              -- 'simulee' ou 'SIG'
);

CREATE TABLE dwh.dim_capteur (
    sk_capteur            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_capteur            text NOT NULL UNIQUE,
    type_capteur          text,
    date_installation     date,
    statut                text
);

